const now = new Date();
const formatDate = (daysOffset) => {
  const d = new Date(now);
  d.setDate(d.getDate() + daysOffset);
  return d.toISOString().split('T')[0];
};
const formatISO = (hoursOffset) => {
  const d = new Date(now);
  d.setHours(d.getHours() + hoursOffset);
  return d.toISOString();
};

